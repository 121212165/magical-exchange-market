XIN = 120.0
months = 66

def dca(w_btc, w_eos, w_xin):
    sh = {'b':0.0,'e':0.0,'x':0.0}; inv = 0.0; mv = 0.0
    for i in range(months):
        inv += 1000
        sh['b'] += 1000*w_btc/BTC[i]
        sh['e'] += 1000*w_eos/EOS[i]
        sh['x'] += 1000*w_xin/XIN
    mv = sh['b']*BTC[-1] + sh['e']*EOS[-1] + sh['x']*XIN
    return inv, mv, mv/inv-1

