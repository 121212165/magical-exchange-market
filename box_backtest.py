months = len(BTC)
assert months == 66 and len(EOS) == 66

# 每月定投等值 $1,000,分两种情景
# A: 100% BTC
# B: 模拟BOX近似权重 70%BTC + 20%EOS + 10%XIN(XIN按横盘$120近似)
XIN = 120.0
def dca(weight):
    shares = {'btc':0.0,'eos':0.0,'xin':0.0}
    invested = 0.0
    rows = []
    for i in range(months):
        invested += 1000
        alloc = {'btc':1000*weight[0], 'eos':1000*weight[1], 'xin':1000*weight[2]}
        shares['btc'] += alloc['btc']/BTC[i]
        shares['eos'] += alloc['eos']/EOS[i]
        shares['xin'] += alloc['xin']/XIN
        mv = shares['btc']*BTC[i] + shares['eos']*EOS[i] + shares['xin']*XIN
        rows.append((i+1, invested, mv, mv/invested-1))
    return rows

def fmt(r):
    return f"第{r[0]:>2}个月  投入${r[1]:>7,.0f}  市值${r[2]:>8,.0f}  收益率{r[3]*100:>7.1f}%"

A = dca((1.0,0.0,0.0))
B = dca((0.7,0.2,0.1))

print("="*70)
print("情景A: 每月$1,000 全部定投 BTC (2019-07 ~ 2024-12, 66个月)")
print("="*70)
# 打印每6个月
for r in A[::6]:
    print(fmt(r))
